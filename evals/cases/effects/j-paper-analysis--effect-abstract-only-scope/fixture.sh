ToolPlan: Planning Tool Calls with Learned Cost Models

Abstract. Agents that call external tools waste budget on redundant calls. We introduce ToolPlan, which
learns a cost model for each tool and plans call sequences under a budget. On AgentBenchX, ToolPlan
improves pass@1 from 41.2% to 47.8% over the strongest baseline while using fewer tool calls.

